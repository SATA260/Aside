/** 同一天得到同一句。`date` 形如 2026-10-14。 */
export function quoteFor(date: string): string {
  const [year, month, day] = date.split("-").map(Number);
  const days = Math.floor(Date.UTC(year, month - 1, day) / 86_400_000);
  const index = ((days % QUOTES.length) + QUOTES.length) % QUOTES.length;
  return QUOTES[index];
}

/** 距考试还有几天。日期还没到或已经过去，返回 null。 */
export function daysUntilExam(today: string, exam: string): number | null {
  const toUtc = (value: string) => {
    const [year, month, day] = value.split("-").map(Number);
    return Date.UTC(year, month - 1, day);
  };
  const days = Math.round((toUtc(exam) - toUtc(today)) / 86_400_000);
  return days >= 0 ? days : null;
}
